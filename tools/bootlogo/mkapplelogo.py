#!/usr/bin/env python3
"""Generate shim/applelogo.h from an iOS root's ProgressUI boot logo.

This is the S21 port of Jesvi-iOS's tools/bootlogo/mkbootlogo.py: that project
paints ProgressUI.framework/apple-logo@3x~iphone.png into the firmware GOP
framebuffer from xnuloader/loader.c:boot_logo() before iOS starts. We have no
xnuloader/UEFI stage, but our shim owns the same panel framebuffer
(FB_BASE 0xfa000000, 1080x2400), so the picture is painted there instead.

    python3 tools/bootlogo/mkapplelogo.py [--png PATH] [--out PATH]

Apple's artwork is read at build time and never committed. The generated
header is RLE coverage (value, run) byte pairs, rows of APPLELOGO_W; loader.c
draws it white-on-black, centered. Without the header the shim still builds
(it is included with __has_include) and the screen stays as before.
"""
import argparse
import os
import struct
import sys
import zlib

DEFAULT_PNG = "/home/tom/pf_stage/ProgressUI.framework/apple-logo@3x~iphone.png"
DEFAULT_OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__)))), "shim", "applelogo.h")


def read_cgbi(path):
    """Apple CgBI PNG (BGRA, premultiplied, raw deflate) -> (w, h, coverage)."""
    d = open(path, "rb").read()
    if d[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("not a PNG: %s" % path)
    i, cgbi, idat, w, h, ctype = 8, False, b"", None, None, None
    while i < len(d):
        n, t = struct.unpack(">I4s", d[i:i + 8])
        body = d[i + 8:i + 8 + n]
        if t == b"CgBI":
            cgbi = True
        elif t == b"IHDR":
            w, h, depth, ctype, _, _, interlace = struct.unpack(">IIBBBBB", body)
            if depth != 8 or ctype not in (6, 2, 0, 4) or interlace:
                raise ValueError("unsupported PNG format")
        elif t == b"IDAT":
            idat += body
        i += 12 + n
    raw = zlib.decompress(idat, -15) if cgbi else zlib.decompress(idat)
    bpp = {6: 4, 2: 3, 0: 1, 4: 2}[ctype]
    stride = w * bpp
    out, prev, p = bytearray(), bytearray(stride), 0
    for _ in range(h):
        f = raw[p]
        line = bytearray(raw[p + 1:p + 1 + stride])
        p += 1 + stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if f == 1:
                line[x] = (line[x] + a) & 255
            elif f == 2:
                line[x] = (line[x] + b) & 255
            elif f == 3:
                line[x] = (line[x] + ((a + b) >> 1)) & 255
            elif f == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                pred = a if pa <= pb and pa <= pc else b if pb <= pc else c
                line[x] = (line[x] + pred) & 255
        out += line
        prev = line
    cov = bytearray(w * h)
    for k in range(w * h):
        px = out[k * bpp:(k + 1) * bpp]
        if ctype == 6:
            cov[k] = px[3]
        elif ctype == 2:
            cov[k] = max(px)
        elif ctype == 0:
            cov[k] = px[0]
        else:
            cov[k] = px[1]
    if ctype == 6 and min(cov) == 255:          # opaque RGBA: luminance
        for k in range(w * h):
            cov[k] = max(out[k * 4:k * 4 + 3])
    return w, h, bytes(cov)


def rle(cov):
    """(value, run) byte pairs, runs up to 255 (Jesvi's encoding)."""
    out, i = bytearray(), 0
    while i < len(cov):
        v, n = cov[i], 1
        while i + n < len(cov) and cov[i + n] == v and n < 255:
            n += 1
        out += bytes((v, n))
        i += n
    return bytes(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--png", default=DEFAULT_PNG)
    ap.add_argument("--out", default=DEFAULT_OUT)
    a = ap.parse_args()
    if not os.path.isfile(a.png):
        sys.exit("mkapplelogo: no PNG at %s (--png PATH)" % a.png)
    w, h, cov = read_cgbi(a.png)
    data = rle(cov)
    with open(a.out, "w") as f:
        f.write("/* GENERATED by tools/bootlogo/mkapplelogo.py from an iOS root "
                "(ProgressUI apple-logo@3x~iphone.png).\n"
                " * Apple artwork: do not commit. Coverage 0..255 as (value, run) pairs, rows of APPLELOGO_W. */\n")
        f.write("#define APPLELOGO_W %d\n#define APPLELOGO_H %d\n" % (w, h))
        f.write("static const unsigned char applelogo_rle[] = {\n")
        for i in range(0, len(data), 24):
            f.write("\t" + ", ".join("%d" % b for b in data[i:i + 24]) + ",\n")
        f.write("};\n")
    print("mkapplelogo: %s: %dx%d -> %d RLE bytes" % (a.out, w, h, len(data)))


if __name__ == "__main__":
    main()
